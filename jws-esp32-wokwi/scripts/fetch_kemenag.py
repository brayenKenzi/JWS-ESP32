"""Fetch the public table used by the official Bimas Islam webpage.

No API key, third-party mirror, credentials, or synthetic astronomical data.
This public webpage proxy is distinct from the private SIHAT developer API.
Example: python fetch_kemenag.py --year 2026 --output kotamobagu-2026.json
"""
import argparse
import calendar
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import urllib.parse
import urllib.request

BASE = "https://bimasislam.kemenag.go.id"
FIELDS = ["imsak", "subuh", "terbit", "dzuhur", "ashar", "maghrib", "isya"]


def get_json(path):
    url = BASE + "/api/sihat/" + path
    request = urllib.request.Request(url, headers={"Accept": "application/json", "User-Agent": "JWS-ESP32-official-timetable-import/1.0"})
    with urllib.request.urlopen(request, timeout=30) as response:
        body = response.read()
    return json.loads(body), url, body


def minute(value):
    if not isinstance(value, str) or not re.fullmatch(r"(?:[01]\d|2[0-3]):[0-5]\d", value):
        raise ValueError(f"Invalid time {value!r}")
    hour, minutes = map(int, value.split(":"))
    return hour * 60 + minutes


def normalize(months, year, province_name, city_name):
    days = []
    sources = []
    for month, (data, source, body, fetched_at) in enumerate(months, 1):
        if data.get("status") != 1 or data.get("kabko") != city_name or data.get("prov") != province_name:
            raise ValueError(f"Wrong source region/status for month {month}")
        expected = calendar.monthrange(year, month)[1]
        if len(data.get("data", {})) != expected:
            raise ValueError(f"Incomplete month {month}")
        for day in range(1, expected + 1):
            date = f"{year:04d}-{month:02d}-{day:02d}"
            row = data["data"].get(date)
            if not row:
                raise ValueError(f"Missing official day {date}")
            values = [minute(row[field]) for field in FIELDS]
            if any(a >= b for a, b in zip(values, values[1:])):
                raise ValueError(f"Invalid time order {date}")
            days.append({"date": date, "minutes": values})
        sources.append({"month": month, "url": source, "retrievedAt": fetched_at,
                        "sha256": hashlib.sha256(body).hexdigest()})
    expected_days = 366 if calendar.isleap(year) else 365
    if len(days) != expected_days:
        raise ValueError("Incomplete official year")
    first = months[0][0]
    return {
        "schema": 1, "authority": "Kementerian Agama Republik Indonesia",
        "source": "kemenag", "sourcePage": BASE + "/jadwal-sholat",
        "region": {"province": province_name, "city": city_name,
                   "timezone": "Asia/Makassar", "utcOffsetMinutes": 480,
                   "latitude": 0.7373333333, "longitude": 124.3166527778,
                   "latitudeDms": first.get("lintang"), "longitudeDms": first.get("bujur")},
        "year": year, "fields": FIELDS, "days": days,
        "provenance": sources,
        "notes": "Official city/regency table; no extra ihtiyat or corrections applied. Terbit maps to Syuruq. Corrections must be applied separately."
    }



def write_header(data, json_bytes, destination):
    lines = ['// Official Kementerian Agama Republik Indonesia timetable; generated by fetch_kemenag.py.',
             '// https://bimasislam.kemenag.go.id/jadwal-sholat', '#pragma once', '#include <stdint.h>',
             'namespace jws {', 'constexpr int KemenagBuiltInYear = %d;' % data['year'],
             'static const uint16_t KemenagBuiltInMinutes[%d][7] = {' % len(data['days'])]
    for day in data['days']:
        lines.append('  {' + ','.join(map(str, day['minutes'])) + '}, // ' + day['date'])
    lines += ['};', 'static const char KemenagFetchedAt[] = ' + json.dumps(min(p['retrievedAt'] for p in data['provenance'])) + ';',
              'static const char KemenagSourceUrl[] = ' + json.dumps(data['sourcePage']) + ';',
              'static const char KemenagDataSha256[] = ' + json.dumps(hashlib.sha256(json_bytes).hexdigest()) + ';', '} // namespace jws', '']
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text('\n'.join(lines), encoding='utf-8')

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--year", type=int, default=2026)
    parser.add_argument("--output", type=Path, default=Path("data/kemenag-kotamobagu-2026.json"))
    parser.add_argument("--from-saved", type=Path, help="Validate saved raw monthly evidence instead of fetching")
    parser.add_argument("--header", type=Path, default=Path("include/KemenagData.h"))
    args = parser.parse_args()
    if not 2000 <= args.year <= 2099:
        parser.error("Year must be 2000..2099")
    province_name, city_name = "SULAWESI UTARA", "KOTA KOTAMOBAGU"
    months = []
    if args.from_saved:
        for month in range(1, 13):
            name = f"kotamobagu-{args.year}-{month:02d}"
            raw_path = args.from_saved / (name + "-raw.json")
            body = raw_path.read_bytes()
            data = json.loads(body.decode("utf-8-sig"))
            provenance = json.loads((args.from_saved / (name + "-provenance.json")).read_text(encoding="utf-8-sig"))
            months.append((data, provenance["sourceUrl"], body, provenance["retrievedAt"]))
    else:
        provinces, _, _ = get_json("provinsi")
        province = next(item for item in provinces["data"] if item["name"] == province_name)
        cities, _, _ = get_json("kabko?" + urllib.parse.urlencode({"prov": province["id"]}))
        city = next(item for item in cities["data"] if item["name"] == city_name)
        for month in range(1, 13):
            query = urllib.parse.urlencode({"prov": province["id"], "kabko": city["id"], "thn": args.year, "bln": f"{month:02d}"})
            data, url, body = get_json("jadwal?" + query)
            months.append((data, url, body, datetime.now(timezone.utc).isoformat()))
    output = normalize(months, args.year, province_name, city_name)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(output, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    write_header(output, args.output.read_bytes(), args.header)
    print(f"Validated {len(output['days'])} official days for {city_name}; wrote {args.output}")


if __name__ == "__main__":
    main()
