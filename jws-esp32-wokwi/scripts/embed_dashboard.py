"""Embed deterministic gzip dashboard assets in ESP32 flash; also usable standalone."""
from pathlib import Path
import gzip
import hashlib


def generate(root):
    pieces = ['// Generated by scripts/embed_dashboard.py; edit web/ source files.',
              '#pragma once', '#include <Arduino.h>', '#include <stddef.h>', '']
    for file_name, symbol in [('index.html', 'dashboardIndexGz'), ('style.css', 'dashboardCssGz'), ('app.js', 'dashboardJsGz')]:
        source = root / 'web' / file_name
        raw = source.read_bytes().replace(b'\r\n', b'\n')
        data = gzip.compress(raw, compresslevel=9, mtime=0)
        pieces.append('// %s; SHA256 %s' % (file_name, hashlib.sha256(raw).hexdigest()))
        pieces.append('static const uint8_t %s[] PROGMEM = {' % symbol)
        for offset in range(0, len(data), 20):
            pieces.append('  ' + ','.join('0x%02x' % value for value in data[offset:offset+20]) + ',')
        pieces += ['};', 'static constexpr size_t %sLen = sizeof %s;' % (symbol, symbol), '']
    output = root / 'include' / 'DashboardAssets.h'
    content = '\n'.join(pieces) + '\n'
    if not output.exists() or output.read_text(encoding='utf-8') != content:
        output.write_text(content, encoding='utf-8')


try:
    Import('env')  # Provided by PlatformIO/SCons.
except NameError:
    if __name__ == '__main__':
        generate(Path(__file__).resolve().parents[1])
else:
    generate(Path(env['PROJECT_DIR']))
